create or replace function public.create_order_internal(
  p_customer_name text,
  p_customer_phone text,
  p_customer_address text,
  p_notes text,
  p_items jsonb,
  p_language text default 'ar',
  p_session_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare
  new_order public.orders%rowtype;
  item jsonb;
  product public.products%rowtype;
  item_quantity integer;
  item_product_id bigint;
  running_total numeric(12,2) := 0;
  seen_ids bigint[] := array[]::bigint[];
  response_items jsonb;
  product_label text;
begin
  if length(trim(coalesce(p_customer_name, ''))) not between 2 and 100
     or length(trim(coalesce(p_customer_phone, ''))) not between 6 and 30
     or length(coalesce(p_customer_address, '')) > 300
     or length(coalesce(p_notes, '')) > 1000
     or p_language not in ('ar','en','fr')
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) not between 1 and 25 then
    raise exception using errcode = '22023', message = 'invalid order payload';
  end if;

  insert into public.orders(customer_name, customer_phone, customer_address, notes, status, total_amount)
  values (trim(p_customer_name), trim(p_customer_phone), nullif(trim(p_customer_address), ''), nullif(trim(p_notes), ''), 'new', 0)
  returning * into new_order;

  for item in select value from jsonb_array_elements(p_items) loop
    begin
      item_product_id := (item ->> 'product_id')::bigint;
      item_quantity := (item ->> 'quantity')::integer;
    exception when others then
      raise exception using errcode = '22023', message = 'invalid order item';
    end;
    if item_quantity not between 1 and 50 or item_product_id = any(seen_ids) then
      raise exception using errcode = '22023', message = 'invalid order item';
    end if;
    seen_ids := array_append(seen_ids, item_product_id);
    select * into product from public.products where id = item_product_id for share;
    if not found or product.price < 0 or product.price > 100000000 then
      raise exception using errcode = '22023', message = 'product unavailable';
    end if;
    product_label := case p_language
      when 'en' then coalesce(nullif(trim(product.name_en), ''), product.name)
      when 'fr' then coalesce(nullif(trim(product.name_fr), ''), nullif(trim(product.name_en), ''), product.name)
      else coalesce(nullif(trim(product.name), ''), product.name_en, product.name_fr)
    end;
    insert into public.order_items(order_id, product_id, product_name, product_category, unit_price, quantity)
    values (new_order.id, product.id, product_label, product.category, product.price, item_quantity);
    running_total := running_total + round(product.price * item_quantity, 2);
  end loop;

  if running_total <= 0 or running_total > 100000000 then
    raise exception using errcode = '22023', message = 'invalid order total';
  end if;
  update public.orders set total_amount = running_total where id = new_order.id returning * into new_order;

  insert into public.analytics_events(event_type, page, session_id, language, metadata)
  values ('order_created', '/checkout', p_session_id, p_language, jsonb_build_object('order_id', new_order.id));

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', oi.id, 'product_id', oi.product_id, 'product_name', oi.product_name,
    'unit_price', oi.unit_price, 'quantity', oi.quantity, 'line_total', oi.line_total
  ) order by oi.id), '[]'::jsonb) into response_items
  from public.order_items oi where oi.order_id = new_order.id;

  return jsonb_build_object(
    'id', new_order.id, 'customer_name', new_order.customer_name,
    'customer_phone', new_order.customer_phone, 'customer_address', new_order.customer_address,
    'notes', new_order.notes, 'total_amount', new_order.total_amount,
    'status', new_order.status, 'created_at', new_order.created_at, 'items', response_items
  );
end;
$$;

revoke all on function public.create_order_internal(text,text,text,text,jsonb,text,uuid) from public, anon, authenticated;
grant execute on function public.create_order_internal(text,text,text,text,jsonb,text,uuid) to service_role;

create or replace function public.audit_admin_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare row_id text; action_name text; details jsonb := '{}'::jsonb;
begin
  if not public.is_admin() then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;
  if tg_op = 'DELETE' then row_id := old.id::text; else row_id := new.id::text; end if;
  action_name := tg_table_name || '_' || lower(tg_op);
  if tg_table_name = 'orders' and tg_op = 'UPDATE' then
    details := jsonb_build_object('old_status', old.status, 'new_status', new.status);
  end if;
  insert into public.admin_audit_logs(admin_user_id, action, entity_type, entity_id, metadata)
  values (auth.uid(), action_name, tg_table_name, row_id, details);
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

revoke all on function public.audit_admin_change() from public, anon, authenticated;

do $$
