-- Keep the rate-limit table compact when a scheduler calls this function.
create or replace function public.prune_rate_limit_buckets()
returns void language sql security definer set search_path = public, pg_catalog
as $$ delete from public.rate_limit_buckets where window_started_at < now() - interval '2 days'; $$;
revoke all on function public.prune_rate_limit_buckets() from public, anon, authenticated;
grant execute on function public.prune_rate_limit_buckets() to service_role;
