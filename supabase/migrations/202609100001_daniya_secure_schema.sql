create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  name_en text,
  name_fr text,
  description text,
  description_en text,
  description_fr text,
  category text not null,
  price numeric(12,2) not null,
  image text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.advertisements (
  id bigint generated by default as identity primary key,
  image_url text not null,
  link text,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null,
  translation_en text,
  translation_fr text,
  category text not null default 'products',
  media_type text not null default 'image',
  storage_path text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text not null,
  email text,
  phone text,
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role = 'admin'),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_phone text not null,
  customer_address text,
  notes text,
  total_amount numeric(12,2) not null default 0,
  status text not null default 'new' check (status in ('new','confirmed','preparing','completed','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  product_category text,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 50),
  line_total numeric(12,2) generated always as (round(unit_price * quantity, 2)) stored,
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id uuid primary key default gen_random_uuid(),
  event_type text not null check (event_type in (
    'page_view','product_view','product_click','product_search','category_filter',
    'add_to_cart','remove_from_cart','cart_view','checkout_started','order_created','whatsapp_order_opened'
  )),
  product_id bigint references public.products(id) on delete set null,
  category text,
  page text,
  session_id uuid,
  language text check (language in ('ar','en','fr')),
  device_type text check (device_type in ('mobile','tablet','desktop')),
  referrer text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint analytics_metadata_object check (jsonb_typeof(metadata) = 'object'),
  constraint analytics_metadata_size check (octet_length(metadata::text) <= 2048)
);

create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  admin_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.rate_limit_buckets (
  scope text not null,
  key_hash text not null,
  window_started_at timestamptz not null default now(),
  request_count integer not null default 1 check (request_count > 0),
  primary key (scope, key_hash)
);

