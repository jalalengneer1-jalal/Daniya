    execute format('create trigger audit_admin_%I after insert or update or delete on public.%I for each row execute function public.audit_admin_change()', table_name, table_name);
  end loop;
end $$;

create or replace function public.admin_dashboard_summary()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_catalog
as $$
declare day_start timestamptz; result jsonb;
begin
  if not public.is_admin() then raise exception using errcode = '42501', message = 'not authorized'; end if;
  day_start := date_trunc('day', now() at time zone 'Africa/Djibouti') at time zone 'Africa/Djibouti';
  select jsonb_build_object(
    'visitors_today', (select count(distinct session_id) from public.analytics_events where event_type = 'page_view' and created_at >= day_start and session_id is not null),
    'orders_today', (select count(*) from public.orders where created_at >= day_start),
    'revenue_today', (select coalesce(sum(total_amount),0) from public.orders where created_at >= day_start and status <> 'cancelled'),
    'new_orders', (select count(*) from public.orders where status = 'new'),
    'total_products', (select count(*) from public.products),
    'total_contacts', (select count(*) from public.contacts),
    'most_viewed_product', (select product_id from public.analytics_events where event_type = 'product_view' and product_id is not null group by product_id order by count(*) desc limit 1),
    'best_selling_product', (select product_id from public.order_items oi join public.orders o on o.id = oi.order_id where o.status <> 'cancelled' group by product_id order by sum(quantity) desc nulls last limit 1),
    'recent_orders', (select coalesce(jsonb_agg(row_to_json(x)), '[]'::jsonb) from (select id,customer_name,total_amount,status,created_at from public.orders order by created_at desc limit 6) x),
    'recent_contacts', (select coalesce(jsonb_agg(row_to_json(x)), '[]'::jsonb) from (select id,name,message,created_at from public.contacts order by created_at desc limit 6) x)
  ) into result;
  return result;
end;
$$;

