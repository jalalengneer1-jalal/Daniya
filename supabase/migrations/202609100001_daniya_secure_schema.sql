create or replace function public.admin_analytics_report(p_from timestamptz, p_to timestamptz)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_catalog
as $$
declare result jsonb;
begin
  if not public.is_admin() then raise exception using errcode = '42501', message = 'not authorized'; end if;
  if p_from is null or p_to is null or p_from > p_to or p_to - p_from > interval '366 days' then
    raise exception using errcode = '22023', message = 'invalid date range';
  end if;

  with behavior as (
    select product_id,
      count(*) filter (where event_type = 'product_view')::int views,
      count(*) filter (where event_type = 'product_click')::int clicks,
      count(*) filter (where event_type = 'add_to_cart')::int cart_adds,
      count(*) filter (where event_type = 'remove_from_cart')::int cart_removals
    from public.analytics_events where created_at between p_from and p_to and product_id is not null group by product_id
  ), sales as (
    select oi.product_id, count(distinct oi.order_id)::int orders, sum(oi.quantity)::int ordered_units, coalesce(sum(oi.line_total),0) revenue
    from public.order_items oi join public.orders o on o.id = oi.order_id
    where o.created_at between p_from and p_to and o.status <> 'cancelled' and oi.product_id is not null group by oi.product_id
  ), product_report as (
    select p.id product_id, p.name, p.name_en, p.name_fr,
      coalesce(b.views,0) views, coalesce(b.clicks,0) clicks, coalesce(b.cart_adds,0) cart_adds,
      coalesce(b.cart_removals,0) cart_removals, coalesce(s.ordered_units,0) ordered_units,
      coalesce(s.orders,0) orders, coalesce(s.revenue,0) revenue,
      round(coalesce(b.cart_adds * 100.0 / nullif(b.views,0),0),1) view_to_cart,
      round(coalesce(s.orders * 100.0 / nullif(b.cart_adds,0),0),1) cart_to_order,
      round(coalesce(s.orders * 100.0 / nullif(b.views,0),0),1) overall_conversion
    from public.products p left join behavior b on b.product_id = p.id left join sales s on s.product_id = p.id
  ), daily as (
    select d::date as "day",
      (select count(distinct e.session_id) from public.analytics_events e where e.event_type='page_view' and e.session_id is not null and e.created_at >= d and e.created_at < d + interval '1 day')::int visitors,
      (select count(*) from public.orders o where o.created_at >= d and o.created_at < d + interval '1 day')::int orders,
      (select coalesce(sum(o.total_amount),0) from public.orders o where o.status <> 'cancelled' and o.created_at >= d and o.created_at < d + interval '1 day') revenue
    from generate_series(date_trunc('day', p_from), date_trunc('day', p_to), interval '1 day') d
  ), category_behavior as (
    select category,
      count(*) filter (where event_type='product_view')::int views,
      count(*) filter (where event_type='add_to_cart')::int cart_adds
    from public.analytics_events where created_at between p_from and p_to and category is not null group by category
  ), category_sales as (
    select oi.product_category category, count(distinct oi.order_id)::int orders, coalesce(sum(oi.line_total),0) revenue
    from public.order_items oi join public.orders o on o.id=oi.order_id
    where o.created_at between p_from and p_to and o.status <> 'cancelled' and oi.product_category is not null group by oi.product_category
  ), category_report as (
    select c.category, coalesce(b.views,0) views, coalesce(b.cart_adds,0) cart_adds, coalesce(s.orders,0) orders, coalesce(s.revenue,0) revenue
    from (values ('dates'),('honey'),('nuts'),('spices'),('food'),('oils')) c(category)
    left join category_behavior b on b.category=c.category left join category_sales s on s.category=c.category
  )
  select jsonb_build_object(
    'kpis', jsonb_build_object(
      'visitors', (select count(distinct session_id) from public.analytics_events where event_type='page_view' and session_id is not null and created_at between p_from and p_to),
      'product_views', (select count(*) from public.analytics_events where event_type='product_view' and created_at between p_from and p_to),
      'cart_adds', (select count(*) from public.analytics_events where event_type='add_to_cart' and created_at between p_from and p_to),
      'orders', (select count(*) from public.orders where created_at between p_from and p_to),
      'revenue', (select coalesce(sum(total_amount),0) from public.orders where status <> 'cancelled' and created_at between p_from and p_to),
      'conversion_rate', round(coalesce((select count(*) from public.orders where created_at between p_from and p_to) * 100.0 / nullif((select count(distinct session_id) from public.analytics_events where event_type='page_view' and session_id is not null and created_at between p_from and p_to),0),0),1)
    ),
    'daily', (select coalesce(jsonb_agg(row_to_json(d) order by d."day"), '[]'::jsonb) from daily d),
    'products', (select coalesce(jsonb_agg(row_to_json(p) order by revenue desc, ordered_units desc, views desc), '[]'::jsonb) from product_report p),
    'categories', (select coalesce(jsonb_agg(row_to_json(c) order by revenue desc, views desc), '[]'::jsonb) from category_report c),
    'opportunities', (select coalesce(jsonb_agg(row_to_json(o)), '[]'::jsonb) from (
      select product_id,name,name_en,name_fr,views,cart_adds,orders,
        case when views >= 5 and cart_adds * 10 < views then 'high_views_low_carts' else 'high_carts_low_orders' end reason
      from product_report
      where (views >= 5 and cart_adds * 10 < views) or (cart_adds >= 3 and orders * 5 < cart_adds)
      order by views desc, cart_adds desc limit 10
    ) o)
  ) into result;
  return result;
end;
$$;

