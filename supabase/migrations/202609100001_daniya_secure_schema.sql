create or replace function public.consume_rate_limit(
  p_scope text,
  p_key_hash text,
  p_limit integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare
  current_bucket public.rate_limit_buckets%rowtype;
begin
  if p_scope !~ '^[a-z_]{2,40}$' or length(p_key_hash) <> 64 or p_limit < 1 or p_limit > 1000 or p_window_seconds < 10 or p_window_seconds > 86400 then
    return false;
  end if;

  select * into current_bucket from public.rate_limit_buckets
  where scope = p_scope and key_hash = p_key_hash for update;

  if not found then
    insert into public.rate_limit_buckets(scope, key_hash) values (p_scope, p_key_hash);
    return true;
  end if;

  if current_bucket.window_started_at + make_interval(secs => p_window_seconds) <= now() then
    update public.rate_limit_buckets set window_started_at = now(), request_count = 1
    where scope = p_scope and key_hash = p_key_hash;
    return true;
  end if;

  if current_bucket.request_count >= p_limit then return false; end if;
  update public.rate_limit_buckets set request_count = request_count + 1
  where scope = p_scope and key_hash = p_key_hash;
  return true;
end;
$$;

revoke all on function public.consume_rate_limit(text,text,integer,integer) from public, anon, authenticated;
grant execute on function public.consume_rate_limit(text,text,integer,integer) to service_role;

create or replace function public.submit_contact_internal(
  p_name text,
  p_email text,
  p_phone text,
  p_message text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare new_id bigint;
begin
  if length(trim(coalesce(p_name, ''))) not between 2 and 100
     or length(coalesce(p_email, '')) > 160
     or length(coalesce(p_phone, '')) > 30
     or length(trim(coalesce(p_message, ''))) not between 5 and 2000
     or coalesce(p_email, '') !~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception using errcode = '22023', message = 'invalid contact payload';
  end if;
  insert into public.contacts(name,email,phone,message)
  values (trim(p_name), nullif(trim(p_email), ''), nullif(trim(p_phone), ''), trim(p_message))
  returning id into new_id;
  return new_id;
end;
$$;

